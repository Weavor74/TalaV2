"""
scripts/generate_sdk_agent_nodes.py — regenerate the SDK self-documentation nodes
=================================================================================

Walks every module under ``sdk/agent/`` and writes one HTML-NN
documentation node per module (``sdk_agent_<module>.html``), so Tala's
retrieval can see the architecture of her own engine room.

Why this exists as a committed script rather than a one-off: these 53
nodes were originally produced by an ad-hoc script that lived only in a
scratch directory. When an automated rollback deleted ``nodes/`` on
2026-08-11 they could not be regenerated by any supported path and were
simply gone — the single largest block of her self-knowledge. Anything
whose only copy is a throwaway script is a future outage.

Usage
-----
    python scripts/generate_sdk_agent_nodes.py            # write nodes
    python scripts/generate_sdk_agent_nodes.py --dry-run  # list, write nothing

TALA_USER_DATA is pinned to the repository root for the duration of the
run. ``create_documentation_node`` resolves its output through
``resolve_active_nodes_dir()``, so without the pin an unpinned run on a
machine with that variable set writes somewhere else entirely.
"""

from __future__ import annotations

import argparse
import ast
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

# Pin before importing anything that resolves the nodes directory.
os.environ["TALA_USER_DATA"] = str(REPO_ROOT)

from sdk.agent.documentation_nodes import create_documentation_node  # noqa: E402

SKIP_MODULES = {"__init__"}


def _first_sentence(doc: str | None) -> str:
    """
    One-line summary of a docstring.

    Prefers the ``NAME\\n  ident - description`` manpage layout this
    codebase uses throughout; a blind sentence split on those produces
    "NAME" for every symbol, which is useless as a summary.
    """
    if not doc:
        return ""
    lines = [ln.strip() for ln in doc.strip().splitlines() if ln.strip()]
    if not lines:
        return ""

    if lines[0].upper() == "NAME" and len(lines) > 1:
        manpage = lines[1]
        if " - " in manpage:
            return manpage.split(" - ", 1)[1].strip()
        return manpage

    text = " ".join(lines)
    for stop in (". ", "? ", "! "):
        if stop in text:
            return text.split(stop, 1)[0].strip() + stop.strip()
    return text[:300].strip()


def _describe_module(path: Path) -> dict[str, object] | None:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except SyntaxError as exc:
        print(f"  ! {path.name}: unparseable ({exc})")
        return None

    module_doc = _first_sentence(ast.get_docstring(tree))
    classes: list[str] = []
    functions: list[str] = []

    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            methods = [
                f"{m.name}()"
                for m in node.body
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))
                and not m.name.startswith("_")
            ]
            summary = _first_sentence(ast.get_docstring(node))
            entry = f"{node.name} — {summary}" if summary else node.name
            if methods:
                entry += f" (methods: {', '.join(methods[:12])})"
            classes.append(entry)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name.startswith("_"):
                continue
            summary = _first_sentence(ast.get_docstring(node))
            functions.append(f"{node.name}() — {summary}" if summary else f"{node.name}()")

    return {"doc": module_doc, "classes": classes, "functions": functions}


def _semantic_memory(module_name: str, rel_path: str, info: dict[str, object]) -> str:
    parts: list[str] = []
    doc = str(info.get("doc") or "").strip()
    parts.append(
        doc
        or f"{module_name} is a module of Tala's agent SDK, defined in {rel_path}."
    )
    parts.append(f"It lives at {rel_path} within the agent SDK.")

    classes = list(info.get("classes") or [])
    functions = list(info.get("functions") or [])

    if classes:
        parts.append("Classes it defines: " + "; ".join(classes) + ".")
    if functions:
        parts.append("Functions it exposes: " + "; ".join(functions) + ".")
    if not classes and not functions:
        parts.append(
            "It exposes no public classes or functions directly — it is "
            "constants, wiring, or private helpers used elsewhere in the SDK."
        )
    return "\n\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="list modules, write nothing")
    args = parser.parse_args()

    agent_dir = REPO_ROOT / "sdk" / "agent"
    modules = sorted(p for p in agent_dir.glob("*.py") if p.stem not in SKIP_MODULES)
    if not modules:
        print(f"no modules found under {agent_dir}")
        return 1

    print(f"documenting {len(modules)} module(s) from {agent_dir}")
    written = 0
    failed = 0

    for path in modules:
        info = _describe_module(path)
        if info is None:
            failed += 1
            continue

        module_name = f"sdk.agent.{path.stem}"
        rel_path = f"sdk/agent/{path.name}"
        node_id = f"sdk_agent_{path.stem}"
        title = f"SDK Agent: {path.stem.replace('_', ' ').title()}"

        if args.dry_run:
            print(f"  - {node_id}")
            continue

        try:
            create_documentation_node(
                node_id=node_id,
                title=title,
                doc_target=module_name,
                semantic_memory=_semantic_memory(module_name, rel_path, info),
                source_files=[rel_path],
                tags=["html-nn", "documentation", "sdk", "agent", path.stem],
            )
            written += 1
        except Exception as exc:
            print(f"  ! {node_id}: {type(exc).__name__}: {exc}")
            failed += 1

    print(f"\nwritten: {written}   failed: {failed}   (nodes dir: {REPO_ROOT / 'nodes'})")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
