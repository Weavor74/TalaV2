"""
generate_architecture_contract.py — declare how this system differs from default.

Steven, 2026-08-23:

    "This is actually meaningfull you created your prob under default
    understandings of how systems work. But I am building a diffrent type of
    system what needs to happen is systems need to be able to loook at mine and
    determine its default system. Otherwise Ill run into the same problem with
    other remote LLM"

The failure that prompted it: a health probe for "memory" was written against
the default assumption that memory means a database service, so it counted
registrations on ``MemoryManager`` and reported HEALTHY. In this system memory
is the HTML-NN store, which that probe never looked at. The probe was wrong in
a way that *read as correct*, and any model applying ordinary assumptions would
have written the same thing.

Prose describing the architecture already existed and did not prevent it,
because prose answers a reader who has already decided to go and look. What was
missing is a **contract**: a machine-readable declaration, discoverable without
being searched for, that states in what respects the defaults do not hold.

Generated rather than hand-written, and generated by *inspecting the running
system*, so it cannot drift into being a confident description of something
that is no longer true -- which is the failure mode of every architecture
document ever written.

    python scripts/generate_architecture_contract.py
    python scripts/generate_architecture_contract.py --print
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

NODE_ID = "system-architecture-contract"


def _count_nodes() -> tuple[int, dict[str, int]]:
    from collections import Counter
    from sdk.agent.documentation_nodes import resolve_active_nodes_dir

    files = list(resolve_active_nodes_dir().glob("*.html"))
    families = Counter(f.stem.split("-")[0] for f in files)
    return len(files), dict(families.most_common(10))


def _chroma_count() -> int | None:
    try:
        from python.harness import retrieval
        if retrieval.node_collection is None:
            return None
        return retrieval.node_collection.count()
    except Exception:
        return None


async def _pg_counts() -> dict[str, int]:
    out: dict[str, int] = {}
    try:
        import asyncpg
        from python.harness.config import settings
        conn = await asyncpg.connect(dsn=settings.DB_URL, timeout=10)
        try:
            rows = await conn.fetch(
                "SELECT source_type, COUNT(*) n FROM memory_index GROUP BY source_type"
            )
            out = {r["source_type"]: r["n"] for r in rows}
        finally:
            await conn.close()
    except Exception:
        pass
    return out


def _tool_count() -> int:
    try:
        from sdk.agent.tools import ToolRegistry
        return len(ToolRegistry._tools)
    except Exception:
        return 0


async def build_contract() -> dict:
    from python.harness.architecture_facts import all_facts, verification_metadata

    total_nodes, families = _count_nodes()
    chroma = _chroma_count()
    pg = await _pg_counts()
    facts = all_facts()
    # Taken fresh here rather than out of `facts`, so the stamp records when
    # THIS contract was built rather than when the facts happened to be
    # gathered -- and so the function has a caller a reader can follow.
    facts["verification"] = verification_metadata()

    return {
        "contract_version": "2.0",
        "system": "Tala",
        "read_this_first": (
            "This system does not follow several common defaults. Read the "
            "'differs_from_default' entries before reasoning about it, and "
            "prefer the terms defined in 'vocabulary' over their usual "
            "meanings. Applying ordinary assumptions here produces conclusions "
            "that look correct and are not."
        ),

        # -- what words mean here -------------------------------------------
        "vocabulary": {
            "memory": (
                "The HTML Neural Node (HTML-NN) store under nodes/. Not a "
                "database service. Nodes are the record; every index over them "
                "is derived and disposable."
            ),
            "HTML-NN": (
                "A normal HTML document with one parser-readable <article> "
                "carrying identity, node type, execution and memory authority, "
                "semantic-memory prose, typed relationship anchors, and a JSON "
                "state block. It is simultaneously a document, a record, and — "
                "when it declares execution authority — a program."
            ),
            "workflow": (
                "A chain of tool calls passing one step's output into the "
                "next, stored as an HTML-NN and executed from that node."
            ),
            "tool registry": (
                "A collection of HTML-NN (tool-*.html), one per tool, carrying "
                "the argument schema. The Python functions are what execute; "
                "the nodes are the catalogue."
            ),
            "vault": (
                "A tag on a node meaning its sensitive fields are encrypted at "
                "rest. Not a separate store."
            ),
        },

        # -- where an outside system will be wrong ---------------------------
        "differs_from_default": [
            {
                "assumption": "Memory is a database or vector service.",
                "reality": (
                    "Memory is the HTML-NN files. ChromaDB and the Postgres "
                    "memory_index are both derived indexes and can be deleted "
                    "and rebuilt from nodes/ without loss."
                ),
                "consequence_if_assumed": (
                    "Health checks, backups and migrations aimed at the "
                    "database will miss the actual memory entirely."
                ),
            },
            {
                "assumption": "The database is the source of truth.",
                "reality": (
                    "Nodes are. Postgres holds operational state (tasks, "
                    "sessions, providers) and a full-text index; where both "
                    "exist, the node is authoritative and the database is a "
                    "fallback."
                ),
                "consequence_if_assumed": (
                    "Writes that go only to the database are lost on the next "
                    "regeneration from nodes."
                ),
            },
            {
                "assumption": "Application data lives in an OS profile directory.",
                "reality": (
                    "Tala is portable and runs from removable media on any OS. "
                    "The data root is the install directory unless "
                    "TALA_USER_DATA says otherwise. APPDATA, XDG and "
                    "~/Library are deliberately ignored."
                ),
                "consequence_if_assumed": (
                    "Data is written to whichever host machine it happens to "
                    "be plugged into, and does not travel with the install."
                ),
            },
            {
                "assumption": "A configured credential means a working service.",
                "reality": (
                    "Configuration and health are separate. A provider reads "
                    "CONFIGURED until something probes it; only a probe "
                    "produces OK or FAILED."
                ),
                "consequence_if_assumed": (
                    "Dead providers are reported as healthy, which is the "
                    "single most common defect found in this codebase."
                ),
            },
            {
                "assumption": "An empty result means nothing matched.",
                "reality": (
                    "It may mean a subsystem is not wired. Interfaces here are "
                    "expected to distinguish 'found nothing' from 'could not "
                    "look'."
                ),
                "consequence_if_assumed": (
                    "Wiring failures are indistinguishable from empty indexes "
                    "and go unnoticed for months."
                ),
            },
            {
                "assumption": "Local model output can be trusted to be complete.",
                "reality": (
                    "Inference is local-first by requirement; no remote model "
                    "is called for the user's own reasoning."
                ),
                "consequence_if_assumed": None,
            },
        ],

        # -- what actually exists right now, measured ------------------------
        "stores": {
            "html_nn": {
                "role": "system of record",
                "location": "nodes/*.html, under the portable data root",
                "count": total_nodes,
                "families": families,
            },
            "chroma_node_index": {
                "role": "derived vector index over the HTML-NN",
                "indexed": chroma,
                "rebuildable": True,
                "note": "re-indexes lazily on each retrieval call",
            },
            "postgres_memory_index": {
                "role": "derived full-text index over operational memory",
                "by_source_type": pg,
                "rebuildable": True,
                "note": (
                    "holds sessions, skills, learning nodes and profiles. It "
                    "is NOT the HTML-NN store, and asking it about nodes will "
                    "under-report."
                ),
            },
            "postgres_operational": {
                "role": "live state: tasks, providers, contacts, credentials",
                "note": "secrets in these tables are encrypted at rest",
            },
            "hindsight": {
                "role": "optional external OS/screen-context daemon",
                "endpoint": "http://localhost:8080/api/search",
                "required": False,
                "note": (
                    "usually absent. Its absence is not a fault and must not "
                    "count against system health."
                ),
            },
        },

        "capabilities": {
            "registered_tools": _tool_count(),
            "tool_catalogue_nodes": families.get("tool", 0),
            # Read from node_execution, never restated. The hardcoded
            # ["workflow", "flow"] that used to sit here stopped being true the
            # day function, decision and service nodes became executable, and
            # a model asking the contract what it could run was given the wrong
            # answer by the one document it is told to consult first.
            **{k: v for k, v in facts["execution_gates"].items()
               if k not in ("available", "reason")},
        },

        # -- the six things a self-reasoning system gets wrong about itself --
        "data_ownership": facts["data_ownership"],
        "security_model": facts["security_model"],
        "execution_paths": facts["execution_paths"],
        "capability_maturity": facts["capability_maturity"],
        "verification": facts["verification"],

        "how_to_verify": (
            "Do not take this document's word for it. Call "
            "logging.get_system_health for measured subsystem state, "
            "tools.catalogue for the live tool list, and list_executable_nodes "
            "for what can actually be run. Each reports what it observed and "
            "on what basis."
        ),
    }


def _prose(contract: dict) -> str:
    lines = [
        "<p><strong>Read this before reasoning about this system.</strong> "
        f"{contract['read_this_first']}</p>",
        "<h3>What these words mean here</h3><ul>",
    ]
    for term, meaning in contract["vocabulary"].items():
        lines.append(f"<li><strong>{term}</strong>: {meaning}</li>")
    lines.append("</ul><h3>Where ordinary assumptions fail</h3><ul>")
    for item in contract["differs_from_default"]:
        entry = f"<li><em>Assumption:</em> {item['assumption']} <em>Reality:</em> {item['reality']}"
        if item.get("consequence_if_assumed"):
            entry += f" <em>If assumed anyway:</em> {item['consequence_if_assumed']}"
        lines.append(entry + "</li>")
    lines.append("</ul>")

    stores = contract["stores"]
    lines.append(
        "<h3>Stores</h3><p>The system of record is the HTML-NN store: "
        f"{stores['html_nn']['count']} node(s) under nodes/. "
        f"The ChromaDB index holds {stores['chroma_node_index']['indexed']} of them and is "
        "rebuildable from the files. The Postgres full-text index covers "
        "operational memory — sessions, skills, profiles — and is not the "
        "node store; asking it about nodes under-reports. Hindsight is an "
        "optional external daemon whose absence is not a fault.</p>"
    )
    # Data ownership, in the terms that matter for backup and restore.
    own = contract["data_ownership"]
    lines.append("<h3>Which store owns what</h3><p>Authoritative, and not "
                 "reconstructible from anything else:</p><ul>")
    for item in own["authoritative"]:
        lines.append(f"<li><strong>{item['records']}</strong> — {item['store']}. "
                     f"{item['backup']} If lost: {item['if_lost']}</li>")
    lines.append("</ul><p>Derived, and safe to delete:</p><ul>")
    for item in own["derived"]:
        lines.append(f"<li>{item['records']} — {item['store']}, rebuildable from "
                     f"{item['rebuildable_from']}.</li>")
    lines.append("</ul>")
    contradiction = own.get("known_contradiction")
    if contradiction:
        lines.append(f"<p><strong>Known contradiction:</strong> "
                     f"{contradiction['what']} {contradiction['why_it_matters']}</p>")
    lines.append("<p><strong>Restore in this order:</strong> "
                 + "; ".join(own["restore_order"]) + ".</p>")

    # Security, kept in three pieces on purpose.
    sec = contract["security_model"]
    lines.append("<h3>Security: three separate things</h3><ul>")
    lines.append("<li><strong>Renderer isolation</strong> — "
                 f"{sec['renderer_isolation']['what_it_protects']} Flags: "
                 + ", ".join(f"{k}={v}" for k, v in
                             sec["renderer_isolation"]["electron_flags"].items())
                 + ".</li>")
    ipc = sec["ipc_surface"]
    lines.append(f"<li><strong>The IPC surface</strong> — {ipc['what_this_means']}"
                 + (f" {ipc['note']}" if ipc.get("note") else "") + "</li>")
    lines.append("<li><strong>Peer permission checks</strong> — "
                 f"{sec['peer_permission_checks']['what_it_protects']} "
                 + " ".join(f"({i + 1}) {layer}." for i, layer in
                            enumerate(sec["peer_permission_checks"]["layers"]))
                 + f" {sec['peer_permission_checks']['scope_note']}</li>")
    lines.append("<li><strong>Host command execution</strong> — "
                 f"{sec['host_command_execution']['reality']} "
                 f"{sec['host_command_execution']['consequence']}</li>")
    lines.append("</ul>")

    # How anything reaches a tool.
    lines.append("<h3>How work reaches a tool</h3><ul>")
    for route in contract["execution_paths"]:
        state = "" if route["entry_exists"] else " <em>(entry point missing — this "
        state += "" if route["entry_exists"] else "route is described but not present)</em>"
        lines.append(f"<li><strong>{route['path']}</strong> ({route['entry']}): "
                     f"{route['reaches_tools_via']}. Verification: "
                     f"{route['verifies_results']}.{state}</li>")
    lines.append("</ul>")

    # What is actually finished.
    lines.append("<h3>Maturity, with evidence</h3><p>implemented = the code "
                 "exists; tested = a named regression covers it; live-verified = "
                 "observed working outside this machine; experimental = present "
                 "and not to be relied on; unavailable = absent or known "
                 "broken.</p><ul>")
    for claim in contract["capability_maturity"]:
        entry = (f"<li><strong>{claim['capability']}</strong> — "
                 f"{claim['maturity']}")
        if claim.get("evidence_present"):
            entry += f". Evidence: {', '.join(claim['evidence_present'])}"
        if claim.get("limits"):
            entry += f". Limits: {claim['limits']}"
        if claim.get("evidence_missing"):
            entry += (f". <em>EVIDENCE MISSING: {', '.join(claim['evidence_missing'])} "
                      "— treat this claim as unsupported.</em>")
        lines.append(entry + "</li>")
    lines.append("</ul>")

    ver = contract["verification"]
    lines.append(
        f"<h3>When this was true</h3><p>Generated {ver['generated_at']} at commit "
        f"{ver['reviewed_commit'][:12]} ({ver['reviewed_commit_subject']}), working "
        f"tree {'clean' if ver['working_tree_clean'] else 'DIRTY — %d uncommitted file(s)' % ver['uncommitted_files']}. "
        f"Reproduce with: {ver['how_to_reproduce']}</p><ul>"
    )
    for limit in ver["known_limitations"]:
        lines.append(f"<li>{limit}</li>")
    lines.append("</ul>")

    lines.append(f"<p>{contract['how_to_verify']}</p>")
    return "".join(lines)


async def main(show: bool) -> int:
    contract = await build_contract()
    if show:
        print(json.dumps(contract, indent=2))
        return 0

    from sdk.agent.documentation_nodes import create_documentation_node

    result = create_documentation_node(
        node_id=NODE_ID,
        title="Architecture Contract",
        doc_target="tala.architecture",
        node_type="documentation",
        semantic_memory=_prose(contract),
        tags=["architecture", "contract", "ontology", "system",
              "defaults", "orientation", "read-first"],
        state_extra={"architecture_contract": contract},
    )
    print(f"wrote {NODE_ID}: {result.get('path') or result}")
    print(f"  nodes: {contract['stores']['html_nn']['count']}   "
          f"chroma: {contract['stores']['chroma_node_index']['indexed']}   "
          f"tools: {contract['capabilities']['registered_tools']}")
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--print", action="store_true", dest="show",
                    help="print the contract instead of writing the node")
    raise SystemExit(asyncio.run(main(ap.parse_args().show)))
