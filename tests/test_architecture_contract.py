"""
The system declares how it differs from the defaults, so outside systems can
read it instead of assuming.

Steven, 2026-08-23:

    "you created your prob under default understandings of how systems work.
    But I am building a diffrent type of system what needs to happen is systems
    need to be able to loook at mine and determine its default system.
    Otherwise Ill run into the same problem with other remote LLM"

The failure that prompted it is instructive because nothing errored. A health
probe for "memory" was written against the ordinary assumption that memory
means a database service; it counted registrations on MemoryManager, reported
HEALTHY, and never looked at the ChromaDB collection that actually holds the
nodes. Prose describing the architecture already existed at
system-tala-html-nn-memory-runtime and did not prevent it, because prose
answers a reader who has already decided to go and look.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from python.harness.architecture_contract import (
    NODE_ID,
    SECTIONS,
    load_contract,
    orientation_line,
)

NODES = Path("nodes")


def test_the_contract_exists_as_a_node():
    """Per the HTML-NN mandate, the declaration is itself a node."""
    assert (NODES / f"{NODE_ID}.html").exists()


def test_it_loads():
    contract = load_contract()
    assert contract["available"] is True
    for key in ("vocabulary", "differs_from_default", "stores", "capabilities"):
        assert key in contract


def test_it_names_the_assumptions_that_fail():
    """The point is not to describe the system. It is to say where an outside
    reader will be wrong."""
    contract = load_contract()
    entries = contract["differs_from_default"]
    assert len(entries) >= 4

    for entry in entries:
        assert entry["assumption"], "an entry with no assumption warns nobody"
        assert entry["reality"]

    text = json.dumps(entries).lower()
    assert "memory" in text
    assert "portable" in text or "os profile" in text
    assert "configured" in text


def test_memory_is_defined_as_the_node_store():
    """The specific misunderstanding that caused this to be written."""
    meaning = load_contract()["vocabulary"]["memory"].lower()
    assert "html" in meaning and "node" in meaning
    assert "not a database" in meaning


def test_the_derived_indexes_are_named_as_derived():
    stores = load_contract()["stores"]
    assert stores["html_nn"]["role"] == "system of record"
    assert stores["chroma_node_index"]["rebuildable"] is True
    assert stores["postgres_memory_index"]["rebuildable"] is True


def test_an_optional_daemon_is_marked_optional():
    """Hindsight is usually absent; its absence must not read as a fault."""
    hindsight = load_contract()["stores"]["hindsight"]
    assert hindsight["required"] is False
    assert "not a fault" in hindsight["note"]


def test_it_is_measured_not_asserted():
    """A hand-written architecture document drifts into confident fiction. This
    one is generated by inspecting the running system."""
    contract = load_contract()
    on_disk = len(list(NODES.glob("*.html")))
    assert contract["stores"]["html_nn"]["count"] == on_disk, (
        f"the contract claims {contract['stores']['html_nn']['count']} node(s) and "
        f"{on_disk} exist -- re-run scripts/generate_architecture_contract.py. "
        f"A contract that has drifted is worse than none: it is believed."
    )
    assert contract["capabilities"]["registered_tools"] > 0


def test_it_tells_the_reader_how_to_check_it():
    """A document that asks to be believed is the thing that goes stale."""
    how = load_contract()["how_to_verify"]
    assert "logging.get_system_health" in how
    assert "tools.catalogue" in how


def test_a_single_section_can_be_asked_for():
    section = load_contract("vocabulary")
    assert section["available"] is True
    assert section["section"] == "vocabulary"
    assert "memory" in section["vocabulary"]
    # a partial answer still carries the warning: the caller is mid-assumption
    # about everything it did not ask for
    assert section["read_this_first"]


def test_an_unknown_section_lists_the_real_ones():
    result = load_contract("nonsense")
    assert result["available"] is False
    for name in SECTIONS:
        assert name in result["error"]


def test_a_missing_contract_still_steers_the_caller(tmp_path, monkeypatch):
    """A caller asking how the system works is about to make an assumption. An
    exception here sends it back to its defaults, which is the failure this
    exists to prevent."""
    import sdk.agent.documentation_nodes as dn
    monkeypatch.setattr(dn, "resolve_active_nodes_dir", lambda: tmp_path)

    result = load_contract()
    assert result["available"] is False
    assert "do not assume" in result["error"]
    assert "generate_architecture_contract" in result["error"]


def test_the_orientation_line_warns_rather_than_summarises():
    """A summary invites the model to proceed on the summary. A warning plus a
    pointer makes it go and read."""
    line = orientation_line()
    assert "describe_architecture" in line
    assert "default" in line.lower()
    assert len(line) < 700, "an orientation line that long is a summary"


def test_it_is_reachable_without_being_searched_for():
    """Prose already existed and did not prevent the mistake, because it had to
    be looked for. This must be pushed, not found."""
    server = Path("python/harness/server.py").read_text(encoding="utf-8")
    tools = Path("sdk/agent/tools.py").read_text(encoding="utf-8")

    assert "orientation_line()" in server, "no model is told the contract exists"
    assert '"system.architecture_contract"' in server, "no external caller can ask"
    assert 'name="describe_architecture"' in tools, "no agent can ask"


def test_the_orientation_comes_before_the_user_line():
    """Orientation before identity: knowing who you are talking to is no use if
    you are wrong about what you are talking through."""
    server = Path("python/harness/server.py").read_text(encoding="utf-8")
    assert server.index("orientation_line()") < server.index("user_profile import system_prompt_line")
