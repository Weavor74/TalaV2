REFERENCE_MODELFILE = """# Modelfile generated by "ollama show"
FROM D:\\ollama\\models\\blobs\\sha256-abc
TEMPLATE \"\"\"<|start_header_id|>system<|end_header_id|>
{{ .System }}<|eot_id|>\"\"\"
PARAMETER stop <|eot_id|>
PARAMETER stop <|start_header_id|>
"""

GOOD_REPLY = "I am doing well tonight, thank you for asking. The cargo run is quiet, and I have been thinking about the route to Stanton."


class World:
    """A fake machine: records every command, and creates what each real stage would have produced."""

    def __init__(self, tmp_path, monkeypatch):
        self.tmp = tmp_path
        self.calls: list[list[str]] = []
        self.models: set[str] = set()
        self.fail: dict[str, tuple[int, str]] = {}
        self.adapter_bytes = 3_400_000
        self.reply = GOOD_REPLY
        self.corpus = {"real": {"success": True, "included": 190, "new_since": 190, "excluded_by": {}, "scanned": 300},
                       "nodes": {"success": True, "included": 20, "new_since": 20, "excluded_by": {}, "scanned": 25}}

        monkeypatch.setenv("TALA_USER_DATA", str(tmp_path / "data"))
        (tmp_path / "data").mkdir()
        monkeypatch.delenv("TALA_LEARNING", raising=False)
        monkeypatch.setattr(lp, "_exec", self.exec)
        monkeypatch.setattr(lp, "_chat", self.chat)
        monkeypatch.setattr(lp, "_halted", lambda: False)
        src = tmp_path / "llama-src"
        (src / "gguf-py").mkdir(parents=True)
        (src / "convert_hf_to_gguf.py").write_text("# converter", encoding="utf-8")
        self.set_config(llama_cpp_src=str(src))

        from sdk.agent import real_usage_corpus as ruc

        async def real(since=None):
            return self.corpus["real"]

        async def nodes(since=None):
            return self.corpus["nodes"]

        monkeypatch.setattr(ruc, "sync_real_usage_corpus", real)
        monkeypatch.setattr(ruc, "sync_learning_events_corpus", nodes)

    def set_config(self, **updates):
        from sdk.agent import node_learning as nl

        nl.write_config(updates)

    @property
    def kinds(self) -> list[str]:
        out = []
        for call in self.calls:
            joined = " ".join(call)
            if "train_voice_adapter" in joined:
                out.append("train")
            elif "merge_adapter" in joined:
                out.append("merge")
            elif "convert_hf_to_gguf" in joined:
                out.append("convert")
            elif call[:2] == ["ollama", "create"]:
                out.append("create")
            elif call[:2] == ["ollama", "rm"]:
                out.append("rm")
            elif call[:2] == ["ollama", "show"]:
                out.append("show")
            elif call[:2] == ["ollama", "list"]:
                out.append("list")
        return out

    async def exec(self, args, *, timeout_s, env=None, low_priority=False, tail_lines=60):
        self.calls.append([str(a) for a in args])
        text = " ".join(str(a) for a in args)
        for needle, failure in self.fail.items():
            if needle in text:
                return failure
        a = [str(x) for x in args]
        if "train_voice_adapter" in text:
            out = Path(a[a.index("--output") + 1])
            out.mkdir(parents=True, exist_ok=True)
            (out / "adapter_config.json").write_text(json.dumps({"base_model_name_or_path": "unsloth/Llama-3.2-1B-Instruct"}), encoding="utf-8")
            (out / "adapter_model.safetensors").write_bytes(b"w" * self.adapter_bytes)
        elif "merge_adapter" in text:
            out = Path(a[-1])
            out.mkdir(parents=True, exist_ok=True)
            (out / "model.safetensors").write_bytes(b"m" * 1000)
        elif "convert_hf_to_gguf" in text:
            Path(a[a.index("--outfile") + 1]).write_bytes(b"GGUF" + b"\0" * 2_000_000)
        elif a[:2] == ["ollama", "show"]:
            return 0, REFERENCE_MODELFILE
        elif a[:2] == ["ollama", "create"]:
            self.models.add(a[2])
            self.modelfile = Path(a[a.index("-f") + 1]).read_text(encoding="utf-8")
        elif a[:2] == ["ollama", "rm"]:
            self.models.discard(a[2])
        elif a[:2] == ["ollama", "list"]:
            return 0, "NAME ID SIZE\n" + "\n".join(f"{m}:latest abc 1.3 GB" for m in sorted(self.models))
        return 0, ""

    async def chat(self, model, prompt, timeout_s=300.0):
        return self.reply


