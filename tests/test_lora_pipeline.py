"""
The autonomous train -> deploy loop for the voice adapter (sdk/agent/lora_pipeline.py).

What the loop does: sync the corpus (her chat sessions and HTML-NN skills/memories), train a LoRA adapter, merge it into its base,
convert the result to GGUF, import it into Ollama, smoke-test the new model, register it as a local provider, keep one earlier
version, and write a record of the run. It exists in this shape because this Ollama refuses `ADAPTER` and cannot import
safetensors on Windows, and because the embedded main model is a 20B that cannot take a LoRA on this hardware.

A fake runner stands in for training, conversion and Ollama, so every stage and every failure is checked quickly and nothing
real is touched. The real chain was exercised by hand against the real adapter (see the session notes in memory).
"""
